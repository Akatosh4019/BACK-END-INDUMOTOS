CREATE TABLE catalogo_motocicleta (
    id_catalogo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca VARCHAR(120) NOT NULL CHECK (btrim(marca) <> ''),
    modelo VARCHAR(120) NOT NULL CHECK (btrim(modelo) <> ''),
    color VARCHAR(120) NOT NULL CHECK (btrim(color) <> ''),
    id_creador BIGINT REFERENCES usuario(id_usuario),
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_catalogo_motocicleta_combinacion
    ON catalogo_motocicleta (lower(btrim(marca)), lower(btrim(modelo)), lower(btrim(color)));

INSERT INTO catalogo_motocicleta (marca, modelo, color)
SELECT DISTINCT ON (lower(btrim(marca)), lower(btrim(modelo)), lower(btrim(color)))
    btrim(marca), btrim(modelo), btrim(color)
FROM motocicleta
ORDER BY lower(btrim(marca)), lower(btrim(modelo)), lower(btrim(color)), id_motocicleta;

INSERT INTO permiso (codigo, nombre, descripcion)
VALUES ('CATALOGO_GESTIONAR', 'Gestionar catálogo de motocicletas', 'Registrar marcas, modelos y colores')
ON CONFLICT (codigo) DO NOTHING;

INSERT INTO rol_permiso (id_rol, id_permiso)
SELECT r.id_rol, p.id_permiso FROM rol r CROSS JOIN permiso p
WHERE r.codigo IN ('ADMIN', 'INVENTARIOS') AND p.codigo = 'CATALOGO_GESTIONAR'
ON CONFLICT (id_rol, id_permiso) DO NOTHING;
