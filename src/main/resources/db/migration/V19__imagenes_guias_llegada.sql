CREATE TABLE llegada_guia_imagen (
    id_imagen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_llegada BIGINT NOT NULL REFERENCES llegada(id_llegada),
    orden SMALLINT NOT NULL CHECK (orden BETWEEN 1 AND 3),
    nombre_archivo VARCHAR(180) NOT NULL,
    tipo_mime VARCHAR(20) NOT NULL CHECK (tipo_mime IN ('image/jpeg', 'image/png')),
    tamano INTEGER NOT NULL CHECK (tamano BETWEEN 1 AND 5242880),
    contenido BYTEA NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_llegada_guia_orden UNIQUE (id_llegada, orden),
    CONSTRAINT ck_llegada_guia_tamano CHECK (octet_length(contenido) = tamano)
);

CREATE INDEX ix_llegada_guia_imagen_llegada ON llegada_guia_imagen(id_llegada);
