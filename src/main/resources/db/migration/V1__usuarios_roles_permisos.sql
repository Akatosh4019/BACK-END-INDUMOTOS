CREATE TABLE rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_rol_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE permiso (
    id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300)
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol BIGINT NOT NULL REFERENCES rol(id_rol),
    nombre_completo VARCHAR(180) NOT NULL,
    nombre_usuario VARCHAR(80) NOT NULL UNIQUE,
    clave_hash VARCHAR(255) NOT NULL,
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE rol_permiso (
    id_rolpermiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol BIGINT NOT NULL REFERENCES rol(id_rol),
    id_permiso BIGINT NOT NULL REFERENCES permiso(id_permiso),
    CONSTRAINT uq_rol_permiso UNIQUE (id_rol, id_permiso)
);

CREATE TABLE usuario_permiso (
    id_usuariopermiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    id_permiso BIGINT NOT NULL REFERENCES permiso(id_permiso),
    decision VARCHAR(10) NOT NULL,
    CONSTRAINT ck_usuario_permiso_decision CHECK (decision IN ('PERMITIR', 'DENEGAR')),
    CONSTRAINT uq_usuario_permiso UNIQUE (id_usuario, id_permiso)
);

CREATE INDEX ix_usuario_rol ON usuario(id_rol);
CREATE INDEX ix_rol_permiso_permiso ON rol_permiso(id_permiso);
CREATE INDEX ix_usuario_permiso_permiso ON usuario_permiso(id_permiso);
