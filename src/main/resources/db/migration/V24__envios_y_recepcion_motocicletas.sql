-- La ubicación confirmada se mantiene durante el transporte. El envío registra
-- la custodia temporal y vincula cada unidad con su solicitud.
ALTER TABLE llegada ADD COLUMN id_almacen_recepcion BIGINT REFERENCES ubicacion(id_ubicacion);

CREATE TABLE envio_solicitud_motocicleta (
    id_envio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitud_ensamblaje(id_solicitud),
    id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta),
    id_origen BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    id_destino BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    despachado_por BIGINT NOT NULL REFERENCES usuario(id_usuario),
    despachado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recibido_por BIGINT REFERENCES usuario(id_usuario),
    recibido_en TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_envio_solicitud_moto UNIQUE(id_solicitud,id_motocicleta),
    CONSTRAINT ck_envio_recepcion CHECK ((recibido_por IS NULL) = (recibido_en IS NULL)),
    CONSTRAINT ck_envio_origen_destino CHECK (id_origen <> id_destino)
);

CREATE UNIQUE INDEX ux_envio_moto_en_transito
    ON envio_solicitud_motocicleta(id_motocicleta) WHERE recibido_en IS NULL;
CREATE INDEX ix_envio_solicitud ON envio_solicitud_motocicleta(id_solicitud);

