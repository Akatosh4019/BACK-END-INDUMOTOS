CREATE TABLE usuario_tienda (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuario(id_usuario),
    id_tienda BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    id_asignador BIGINT NOT NULL REFERENCES usuario(id_usuario),
    asignada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_usuario_tienda_tienda ON usuario_tienda(id_tienda);

CREATE TABLE venta_motocicleta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_motocicleta BIGINT NOT NULL UNIQUE REFERENCES motocicleta(id_motocicleta),
    id_tienda BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    id_vendedor BIGINT NOT NULL REFERENCES usuario(id_usuario),
    referencia_comprobante VARCHAR(100) NOT NULL,
    importe NUMERIC(12,2) NOT NULL CHECK (importe > 0),
    vendida_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_venta_referencia CHECK (btrim(referencia_comprobante) <> '')
);
CREATE UNIQUE INDEX ux_venta_comprobante ON venta_motocicleta(id_tienda,upper(btrim(referencia_comprobante)));
CREATE INDEX ix_venta_tienda_fecha ON venta_motocicleta(id_tienda,vendida_en DESC);

INSERT INTO permiso(codigo,nombre,descripcion) VALUES
('COMPANIA_CONSULTAR','Consultar compañía','Resumen global de tiendas y ventas'),
('TIENDA_CONSULTAR','Consultar tienda','Stock y ventas de la tienda asignada'),
('VENTAS_REGISTRAR','Registrar venta','Registrar venta con comprobante real')
ON CONFLICT(codigo) DO NOTHING;
INSERT INTO rol_permiso(id_rol,id_permiso)
SELECT r.id_rol,p.id_permiso FROM rol r CROSS JOIN permiso p
WHERE (r.codigo='ADMIN' AND p.codigo='COMPANIA_CONSULTAR')
OR (r.codigo IN ('ADMIN','COMERCIAL','FACTURACION') AND p.codigo='TIENDA_CONSULTAR')
OR (r.codigo IN ('ADMIN','COMERCIAL') AND p.codigo='VENTAS_REGISTRAR')
ON CONFLICT(id_rol,id_permiso) DO NOTHING;
