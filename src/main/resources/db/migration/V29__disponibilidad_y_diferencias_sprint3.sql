CREATE TABLE disponibilidad_evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('HABILITADA','BLOQUEADA')),
    motivo VARCHAR(500) NOT NULL CHECK (btrim(motivo) <> ''),
    id_registrador BIGINT NOT NULL REFERENCES usuario(id_usuario),
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_disponibilidad_evento_moto ON disponibilidad_evento(id_motocicleta,id_evento DESC);

CREATE TABLE diferencia_datos (
    id_diferencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta),
    campo VARCHAR(30) NOT NULL CHECK (campo IN ('marca','modelo','color','chasisCompleto','numeroMotor','dua','itemDua')),
    valor_observado VARCHAR(300) NOT NULL CHECK (btrim(valor_observado) <> ''),
    descripcion VARCHAR(1000) NOT NULL CHECK (btrim(descripcion) <> ''),
    id_reportante BIGINT NOT NULL REFERENCES usuario(id_usuario),
    reportada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','RESUELTA')),
    valor_anterior VARCHAR(300),
    valor_corregido VARCHAR(300),
    fuente VARCHAR(500),
    resolucion VARCHAR(1000),
    id_resolutor BIGINT REFERENCES usuario(id_usuario),
    resuelta_en TIMESTAMPTZ,
    CONSTRAINT ck_diferencia_resuelta CHECK (
        (estado='PENDIENTE' AND id_resolutor IS NULL AND resuelta_en IS NULL)
        OR (estado='RESUELTA' AND id_resolutor IS NOT NULL AND resuelta_en IS NOT NULL
            AND nullif(btrim(fuente),'') IS NOT NULL AND nullif(btrim(resolucion),'') IS NOT NULL)
    )
);
CREATE INDEX ix_diferencia_estado ON diferencia_datos(estado,reportada_en DESC);
CREATE INDEX ix_diferencia_moto ON diferencia_datos(id_motocicleta);
CREATE INDEX ix_diferencia_reportante ON diferencia_datos(id_reportante);

