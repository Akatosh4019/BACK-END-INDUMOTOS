-- HU-16 y HU-17: desactivar o reactivar cuentas sin borrar su historial y consultar accesos.
-- Los tokens emitidos antes de un cambio de estado dejan de ser válidos aunque la cuenta se reactive.
ALTER TABLE usuario ADD COLUMN sesiones_validas_desde TIMESTAMPTZ;

CREATE TABLE usuario_estado_evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    estado_anterior VARCHAR(10) NOT NULL CHECK (estado_anterior IN ('ACTIVO','INACTIVO')),
    estado_nuevo VARCHAR(10) NOT NULL CHECK (estado_nuevo IN ('ACTIVO','INACTIVO')),
    motivo VARCHAR(500) NOT NULL CHECK (btrim(motivo) <> ''),
    id_actor BIGINT NOT NULL REFERENCES usuario(id_usuario),
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_estado_evento_cambio CHECK (estado_anterior <> estado_nuevo)
);
CREATE INDEX ix_usuario_estado_evento_usuario ON usuario_estado_evento(id_usuario, id_evento DESC);
CREATE INDEX ix_usuario_estado_evento_actor ON usuario_estado_evento(id_actor);

INSERT INTO permiso(codigo,nombre,descripcion) VALUES
('USUARIOS_CONSULTAR','Consultar cuentas','HU-17: estado, rol y permisos vigentes'),
('USUARIOS_DESACTIVAR','Desactivar o reactivar cuentas','HU-16: conserva el historial de la cuenta')
ON CONFLICT(codigo) DO NOTHING;

INSERT INTO rol_permiso(id_rol,id_permiso)
SELECT r.id_rol,p.id_permiso FROM rol r CROSS JOIN permiso p
WHERE r.codigo='ADMIN' AND p.codigo IN ('USUARIOS_CONSULTAR','USUARIOS_DESACTIVAR')
ON CONFLICT(id_rol,id_permiso) DO NOTHING;
