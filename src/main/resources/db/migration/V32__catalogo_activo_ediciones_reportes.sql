-- Solicitudes: una solicitud pendiente puede corregirse, pero se guarda lo que
-- se había pedido antes de cada edición.
CREATE TABLE solicitud_ensamblaje_edicion (
    id_edicion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitud_ensamblaje(id_solicitud),
    id_editor BIGINT NOT NULL REFERENCES usuario(id_usuario),
    editada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_destino_anterior BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    observacion_anterior VARCHAR(1000),
    lineas_anteriores VARCHAR(4000) NOT NULL CHECK (btrim(lineas_anteriores) <> '')
);
CREATE INDEX ix_solicitud_edicion ON solicitud_ensamblaje_edicion(id_solicitud, id_edicion DESC);

CREATE TRIGGER trg_solicitud_edicion_inmutable
BEFORE UPDATE OR DELETE ON solicitud_ensamblaje_edicion
FOR EACH ROW EXECUTE FUNCTION impedir_edicion_historial_logistico();

