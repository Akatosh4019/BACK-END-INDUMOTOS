CREATE TABLE motocicleta_ficha (
 id_motocicleta BIGINT PRIMARY KEY REFERENCES motocicleta(id_motocicleta),
 anio INTEGER CHECK(anio BETWEEN 1900 AND 2100), cilindrada INTEGER CHECK(cilindrada BETWEEN 1 AND 5000),
 transmision VARCHAR(80), combustible VARCHAR(80), descripcion VARCHAR(2000), version BIGINT NOT NULL DEFAULT 0,
 id_editor BIGINT NOT NULL REFERENCES usuario(id_usuario), actualizada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE motocicleta_foto (
 id_foto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta),
 contenido BYTEA NOT NULL, mime VARCHAR(20) NOT NULL CHECK(mime IN ('image/png','image/jpeg')),
 sha256 VARCHAR(64) NOT NULL, id_autor BIGINT NOT NULL REFERENCES usuario(id_usuario),
 creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id_motocicleta,sha256)
);
CREATE INDEX ix_moto_foto ON motocicleta_foto(id_motocicleta,id_foto);
CREATE TABLE motocicleta_ficha_evento (
 id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta), datos JSONB NOT NULL,
 id_actor BIGINT NOT NULL REFERENCES usuario(id_usuario), creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TRIGGER trg_ficha_evento_inmutable BEFORE UPDATE OR DELETE ON motocicleta_ficha_evento
FOR EACH ROW EXECUTE FUNCTION impedir_edicion_historial_logistico();
