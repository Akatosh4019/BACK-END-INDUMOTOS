CREATE TABLE bitacora_cambio (
    id_cambio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad VARCHAR(40) NOT NULL,
    entidad_id BIGINT NOT NULL,
    accion VARCHAR(10) NOT NULL,
    datos_antes JSONB,
    datos_despues JSONB,
    actor VARCHAR(80),
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_bitacora_cambio_entidad ON bitacora_cambio(entidad, entidad_id, id_cambio DESC);

CREATE FUNCTION auditar_datos_maestros() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    previo JSONB;
    posterior JSONB;
    identificador BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'usuario' THEN
        previo := jsonb_build_object('nombreCompleto', OLD.nombre_completo, 'nombreUsuario', OLD.nombre_usuario,
            'documento', OLD.documento, 'telefono', OLD.telefono, 'rolId', OLD.id_rol);
        posterior := jsonb_build_object('nombreCompleto', NEW.nombre_completo, 'nombreUsuario', NEW.nombre_usuario,
            'documento', NEW.documento, 'telefono', NEW.telefono, 'rolId', NEW.id_rol);
        identificador := NEW.id_usuario;
    ELSIF TG_TABLE_NAME = 'motocicleta' THEN
        previo := jsonb_build_object('marca', OLD.marca, 'modelo', OLD.modelo, 'color', OLD.color,
            'chasis', OLD.chasis_completo, 'motor', OLD.numero_motor, 'dua', OLD.dua, 'itemDua', OLD.item_dua);
        posterior := jsonb_build_object('marca', NEW.marca, 'modelo', NEW.modelo, 'color', NEW.color,
            'chasis', NEW.chasis_completo, 'motor', NEW.numero_motor, 'dua', NEW.dua, 'itemDua', NEW.item_dua);
        identificador := NEW.id_motocicleta;
    ELSIF TG_TABLE_NAME = 'usuario_permiso' THEN
        previo := CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END;
        posterior := CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END;
        identificador := CASE WHEN TG_OP = 'DELETE' THEN OLD.id_usuario ELSE NEW.id_usuario END;
    ELSE
        previo := CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END;
        posterior := CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END;
        identificador := CASE WHEN TG_OP = 'DELETE' THEN OLD.id_rol ELSE NEW.id_rol END;
    END IF;
    IF previo IS DISTINCT FROM posterior THEN
        INSERT INTO bitacora_cambio(entidad, entidad_id, accion, datos_antes, datos_despues, actor)
        VALUES (TG_TABLE_NAME, identificador, TG_OP, previo, posterior,
            NULLIF(current_setting('indumotos.actor', true), ''));
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE TRIGGER trg_auditar_usuario AFTER UPDATE OF nombre_completo, nombre_usuario, documento, telefono, id_rol
ON usuario FOR EACH ROW EXECUTE FUNCTION auditar_datos_maestros();
CREATE TRIGGER trg_auditar_motocicleta AFTER UPDATE OF marca, modelo, color, chasis_completo, numero_motor, dua, item_dua
ON motocicleta FOR EACH ROW EXECUTE FUNCTION auditar_datos_maestros();
CREATE TRIGGER trg_auditar_usuario_permiso AFTER INSERT OR UPDATE OR DELETE
ON usuario_permiso FOR EACH ROW EXECUTE FUNCTION auditar_datos_maestros();
CREATE TRIGGER trg_auditar_rol_permiso AFTER INSERT OR UPDATE OR DELETE
ON rol_permiso FOR EACH ROW EXECUTE FUNCTION auditar_datos_maestros();
