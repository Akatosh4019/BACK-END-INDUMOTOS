CREATE TABLE pago_venta (
 id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, solicitud UUID NOT NULL UNIQUE,
 id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta), id_tienda BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
 metodo VARCHAR(20) NOT NULL CHECK(metodo IN ('YAPE','PLIN','TRANSFERENCIA')), entidad VARCHAR(80) NOT NULL,
 referencia VARCHAR(100) NOT NULL CHECK(btrim(referencia)<>''), importe NUMERIC(12,2) NOT NULL CHECK(importe>0),
 comprobante BYTEA NOT NULL, mime VARCHAR(20) NOT NULL, sha256 VARCHAR(64) NOT NULL,
 estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE' CHECK(estado IN ('PENDIENTE','CONFIRMADO','RECHAZADO')),
 motivo VARCHAR(500), referencia_venta VARCHAR(100), id_venta BIGINT UNIQUE REFERENCES venta_motocicleta(id_venta),
 id_registrador BIGINT NOT NULL REFERENCES usuario(id_usuario), id_revisor BIGINT REFERENCES usuario(id_usuario),
 registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, revisado_en TIMESTAMPTZ,
 CHECK((estado='PENDIENTE' AND id_revisor IS NULL AND id_venta IS NULL) OR
       (estado='CONFIRMADO' AND id_revisor IS NOT NULL AND id_venta IS NOT NULL AND revisado_en IS NOT NULL) OR
       (estado='RECHAZADO' AND id_revisor IS NOT NULL AND id_venta IS NULL AND btrim(motivo)<>'' AND revisado_en IS NOT NULL))
);
CREATE UNIQUE INDEX ux_pago_pendiente_moto ON pago_venta(id_motocicleta) WHERE estado='PENDIENTE';
CREATE UNIQUE INDEX ux_pago_referencia ON pago_venta(metodo,lower(btrim(entidad)),upper(btrim(referencia)));
CREATE INDEX ix_pago_tienda ON pago_venta(id_tienda,id_pago DESC);
CREATE TABLE pago_evento (
 id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_pago BIGINT NOT NULL REFERENCES pago_venta(id_pago),
 estado VARCHAR(15) NOT NULL,id_actor BIGINT NOT NULL REFERENCES usuario(id_usuario),motivo VARCHAR(500),
 registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TRIGGER trg_pago_evento_inmutable BEFORE UPDATE OR DELETE ON pago_evento FOR EACH ROW EXECUTE FUNCTION impedir_edicion_historial_logistico();
