CREATE TABLE catalogo_modelo (
    id_modelo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca VARCHAR(120) NOT NULL,
    modelo VARCHAR(120) NOT NULL,
    descripcion VARCHAR(1200) NOT NULL DEFAULT '',
    activo BOOLEAN NOT NULL DEFAULT true,
    imagen_mime VARCHAR(20),
    imagen_contenido BYTEA,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_catalogo_modelo_imagen CHECK ((imagen_mime IS NULL) = (imagen_contenido IS NULL)),
    CONSTRAINT ck_catalogo_modelo_mime CHECK (imagen_mime IS NULL OR imagen_mime IN ('image/jpeg', 'image/png')),
    CONSTRAINT ck_catalogo_modelo_tamano CHECK (imagen_contenido IS NULL OR octet_length(imagen_contenido) BETWEEN 1 AND 3145728)
);
CREATE UNIQUE INDEX ux_catalogo_modelo_nombre ON catalogo_modelo(lower(btrim(marca)), lower(btrim(modelo)));
INSERT INTO catalogo_modelo(marca,modelo)
SELECT DISTINCT ON (lower(btrim(marca)),lower(btrim(modelo))) marca,modelo
FROM catalogo_motocicleta
ORDER BY lower(btrim(marca)),lower(btrim(modelo)),id_catalogo;

CREATE FUNCTION auditar_catalogo_modelo() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    previo JSONB;
    posterior JSONB;
BEGIN
    previo := jsonb_build_object('descripcion', OLD.descripcion, 'activo', OLD.activo,
        'tieneImagen', OLD.imagen_contenido IS NOT NULL);
    posterior := jsonb_build_object('descripcion', NEW.descripcion, 'activo', NEW.activo,
        'tieneImagen', NEW.imagen_contenido IS NOT NULL);
    IF previo IS DISTINCT FROM posterior OR OLD.imagen_contenido IS DISTINCT FROM NEW.imagen_contenido THEN
        INSERT INTO bitacora_cambio(entidad,entidad_id,accion,datos_antes,datos_despues,actor)
        VALUES ('catalogo_modelo',NEW.id_modelo,'UPDATE',previo,posterior,
            NULLIF(current_setting('indumotos.actor', true),''));
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_auditar_catalogo_modelo AFTER UPDATE OF descripcion,activo,imagen_contenido
ON catalogo_modelo FOR EACH ROW EXECUTE FUNCTION auditar_catalogo_modelo();
