ALTER TABLE llegada ADD COLUMN eliminado_en TIMESTAMP WITH TIME ZONE;
ALTER TABLE llegada ADD COLUMN eliminado_por BIGINT REFERENCES usuario(id_usuario);
ALTER TABLE llegada ADD COLUMN motivo_eliminacion VARCHAR(500);

CREATE TABLE llegada_evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_llegada BIGINT NOT NULL REFERENCES llegada(id_llegada),
    accion VARCHAR(24) NOT NULL CHECK (accion IN ('RETIRADA', 'RESTAURADA', 'FOTOS_REEMPLAZADAS', 'FOTOS_PURGADAS')),
    usuario_id BIGINT REFERENCES usuario(id_usuario),
    ocurrido_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(500),
    numero_guia VARCHAR(120) NOT NULL,
    CONSTRAINT ck_llegada_evento_motivo CHECK (accion <> 'RETIRADA' OR length(btrim(motivo)) >= 10)
);
CREATE INDEX ix_llegada_evento_llegada ON llegada_evento(id_llegada, ocurrido_en DESC);

-- Los registros históricos ocultos antes de esta migración no se consideran retirados por un usuario.
CREATE UNIQUE INDEX uq_llegada_guia_activa ON llegada (upper(btrim(numero_guia)))
    WHERE visible_en_listado AND eliminado_en IS NULL;
CREATE INDEX ix_llegada_papelera ON llegada(eliminado_en DESC)
    WHERE eliminado_en IS NOT NULL;
