CREATE TABLE llegada (
    id_llegada BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_guia VARCHAR(120) NOT NULL,
    fecha_llegada TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_receptor BIGINT NOT NULL REFERENCES usuario(id_usuario),
    cantidad_declarada INTEGER NOT NULL,
    cantidad_recibida INTEGER NOT NULL,
    observacion VARCHAR(1000),
    CONSTRAINT ck_llegada_cantidad_declarada CHECK (cantidad_declarada > 0),
    CONSTRAINT ck_llegada_cantidad_recibida CHECK (cantidad_recibida > 0)
);

CREATE INDEX ix_llegada_guia ON llegada(numero_guia);
CREATE INDEX ix_llegada_fecha ON llegada(fecha_llegada);
CREATE INDEX ix_llegada_receptor ON llegada(id_receptor);
