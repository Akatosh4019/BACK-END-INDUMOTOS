CREATE TABLE motocicleta (
    id_motocicleta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_llegada BIGINT NOT NULL REFERENCES llegada(id_llegada),
    marca VARCHAR(120) NOT NULL,
    modelo VARCHAR(120) NOT NULL,
    color VARCHAR(120) NOT NULL,
    chasis_completo VARCHAR(120) NOT NULL,
    numero_motor VARCHAR(120) NOT NULL,
    dua VARCHAR(120) NOT NULL,
    item_dua VARCHAR(120) NOT NULL,
    id_creador BIGINT NOT NULL REFERENCES usuario(id_usuario),
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_motocicleta_llegada ON motocicleta(id_llegada);
CREATE INDEX ix_motocicleta_chasis ON motocicleta(chasis_completo);
