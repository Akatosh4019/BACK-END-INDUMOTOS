-- Base logistica de INDUMOTOS.
-- Amplia el Sprint 1 sin inventar sedes ni ubicaciones para motos existentes.

CREATE TABLE ubicacion (
    id_ubicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    referencia VARCHAR(300),
    activo BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT ck_ubicacion_codigo CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_ubicacion_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_ubicacion_tipo CHECK (tipo IN ('ALMACEN', 'TIENDA', 'TALLER'))
);

CREATE UNIQUE INDEX ux_ubicacion_codigo_normalizado
    ON ubicacion (upper(btrim(codigo)));

CREATE TABLE movimiento_motocicleta (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta),
    tipo VARCHAR(20) NOT NULL,
    id_origen BIGINT REFERENCES ubicacion(id_ubicacion),
    id_destino BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    id_registrador BIGINT NOT NULL REFERENCES usuario(id_usuario),
    ocurrido_en TIMESTAMP WITH TIME ZONE NOT NULL,
    registrado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion VARCHAR(1000),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('UBICACION', 'TRASLADO')),
    CONSTRAINT ck_movimiento_origen CHECK (
        (tipo = 'UBICACION' AND id_origen IS NULL)
        OR
        (tipo = 'TRASLADO' AND id_origen IS NOT NULL AND id_origen <> id_destino)
    )
);

CREATE INDEX ix_movimiento_moto
    ON movimiento_motocicleta(id_motocicleta, ocurrido_en DESC, id_movimiento DESC);
CREATE INDEX ix_movimiento_origen ON movimiento_motocicleta(id_origen);
CREATE INDEX ix_movimiento_destino ON movimiento_motocicleta(id_destino);
CREATE INDEX ix_movimiento_registrador ON movimiento_motocicleta(id_registrador);

-- Representa la ultima ubicacion informada; no afirma una posicion en tiempo real.
CREATE VIEW motocicleta_ubicacion_actual AS
SELECT DISTINCT ON (id_motocicleta)
    id_motocicleta,
    id_destino AS id_ubicacion,
    id_movimiento,
    ocurrido_en,
    registrado_en
FROM movimiento_motocicleta
ORDER BY id_motocicleta, ocurrido_en DESC, id_movimiento DESC;

CREATE TABLE solicitud_ensamblaje (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitante BIGINT NOT NULL REFERENCES usuario(id_usuario),
    id_destino BIGINT NOT NULL REFERENCES ubicacion(id_ubicacion),
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion VARCHAR(1000),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_solicitud_version CHECK (version >= 0)
);

CREATE INDEX ix_solicitud_solicitante ON solicitud_ensamblaje(id_solicitante);
CREATE INDEX ix_solicitud_destino ON solicitud_ensamblaje(id_destino);

-- Una solicitud puede pedir varias combinaciones sin conocer aun los chasis.
CREATE TABLE solicitud_ensamblaje_detalle (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitud_ensamblaje(id_solicitud),
    marca VARCHAR(120) NOT NULL,
    modelo VARCHAR(120) NOT NULL,
    color VARCHAR(120) NOT NULL,
    cantidad INTEGER NOT NULL,
    CONSTRAINT ck_detalle_marca CHECK (btrim(marca) <> ''),
    CONSTRAINT ck_detalle_modelo CHECK (btrim(modelo) <> ''),
    CONSTRAINT ck_detalle_color CHECK (btrim(color) <> ''),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0)
);

CREATE INDEX ix_solicitud_detalle ON solicitud_ensamblaje_detalle(id_solicitud);

-- Los cambios de estado se agregan como eventos para conservar la trazabilidad.
CREATE TABLE solicitud_ensamblaje_evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitud_ensamblaje(id_solicitud),
    estado VARCHAR(20) NOT NULL,
    id_registrador BIGINT NOT NULL REFERENCES usuario(id_usuario),
    registrado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(1000),
    CONSTRAINT ck_solicitud_evento_estado CHECK (
        estado IN ('PENDIENTE', 'EN_PREPARACION', 'ATENDIDA', 'RECHAZADA', 'ANULADA')
    ),
    CONSTRAINT ck_solicitud_estado_motivo CHECK (
        estado NOT IN ('RECHAZADA', 'ANULADA')
        OR nullif(btrim(motivo), '') IS NOT NULL
    )
);

CREATE INDEX ix_solicitud_evento
    ON solicitud_ensamblaje_evento(id_solicitud, id_evento DESC);
CREATE INDEX ix_solicitud_evento_usuario
    ON solicitud_ensamblaje_evento(id_registrador);

CREATE VIEW solicitud_ensamblaje_estado_actual AS
SELECT DISTINCT ON (id_solicitud)
    id_solicitud,
    estado,
    id_evento,
    id_registrador,
    registrado_en,
    motivo
FROM solicitud_ensamblaje_evento
ORDER BY id_solicitud, id_evento DESC;

CREATE TABLE solicitud_ensamblaje_unidad (
    id_asociacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_detalle BIGINT NOT NULL REFERENCES solicitud_ensamblaje_detalle(id_detalle),
    id_motocicleta BIGINT NOT NULL REFERENCES motocicleta(id_motocicleta),
    id_asignador BIGINT NOT NULL REFERENCES usuario(id_usuario),
    asociada_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    retirada_en TIMESTAMP WITH TIME ZONE,
    id_retirador BIGINT REFERENCES usuario(id_usuario),
    motivo_retiro VARCHAR(1000),
    CONSTRAINT ck_asociacion_retiro CHECK (
        (retirada_en IS NULL AND id_retirador IS NULL AND motivo_retiro IS NULL)
        OR
        (retirada_en IS NOT NULL
            AND retirada_en >= asociada_en
            AND id_retirador IS NOT NULL
            AND nullif(btrim(motivo_retiro), '') IS NOT NULL)
    )
);

-- Una moto no puede estar asignada simultaneamente a dos solicitudes activas.
CREATE UNIQUE INDEX ux_unidad_solicitud_activa
    ON solicitud_ensamblaje_unidad(id_motocicleta)
    WHERE retirada_en IS NULL;
CREATE INDEX ix_asociacion_detalle ON solicitud_ensamblaje_unidad(id_detalle);
CREATE INDEX ix_asociacion_asignador ON solicitud_ensamblaje_unidad(id_asignador);
CREATE INDEX ix_asociacion_retirador ON solicitud_ensamblaje_unidad(id_retirador);

