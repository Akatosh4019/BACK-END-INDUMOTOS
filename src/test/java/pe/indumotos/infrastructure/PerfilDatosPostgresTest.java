package pe.indumotos.infrastructure;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.Connection;
import java.sql.DriverManager;
import java.nio.charset.StandardCharsets;
import java.util.List;
import org.junit.jupiter.api.*;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.transaction.TransactionStatus;
import org.springframework.transaction.support.DefaultTransactionDefinition;
import org.springframework.web.server.ResponseStatusException;
import pe.indumotos.application.*;
import pe.indumotos.presentation.UsuarioController;

class PerfilDatosPostgresTest {
    private Connection connection;
    private JdbcTemplate jdbc;
    private DataSourceTransactionManager manager;
    private TransactionStatus transaction;
    private PerfilService perfiles;
    private UsuarioController usuarios;

    @BeforeEach void abrir() throws Exception {
        Assumptions.assumeTrue(System.getenv("INDUMOTOS_TEST_DB_URL") != null, "Requiere PostgreSQL de pruebas");
        connection = DriverManager.getConnection(System.getenv("INDUMOTOS_TEST_DB_URL"), System.getenv("INDUMOTOS_TEST_DB_USER"), System.getenv("INDUMOTOS_TEST_DB_PASSWORD"));
        var source = new SingleConnectionDataSource(connection, true);
        manager = new DataSourceTransactionManager(source);
        transaction = manager.getTransaction(new DefaultTransactionDefinition());
        jdbc = new JdbcTemplate(source);
        jdbc.execute("SET LOCAL search_path TO pg_temp");
        jdbc.execute("CREATE TEMP TABLE rol(id_rol bigint PRIMARY KEY,codigo text,nombre text,estado text)");
        jdbc.execute("CREATE TEMP TABLE usuario(id_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_rol bigint,nombre_completo varchar(180) NOT NULL,nombre_usuario text UNIQUE,clave_hash text,estado text DEFAULT 'ACTIVO',sesion_version bigint DEFAULT 0,creado_en timestamptz DEFAULT CURRENT_TIMESTAMP,actualizado_en timestamptz DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TEMP TABLE usuario_tienda(id_usuario bigint,id_tienda bigint,id_asignador bigint)");
        jdbc.execute("CREATE TEMP TABLE ubicacion(id_ubicacion bigint,nombre text,tipo text,activo boolean)");
        jdbc.execute(new ClassPathResource("db/migration/V32__datos_personales_usuario.sql").getContentAsString(StandardCharsets.UTF_8));
        jdbc.update("INSERT INTO rol VALUES(1,'ALMACEN','Almacén','ACTIVO')");
        var encoder = new BCryptPasswordEncoder(4);
        perfiles = new PerfilService(jdbc, encoder);
        usuarios = new UsuarioController(jdbc, encoder);
    }
    @AfterEach void cerrar() throws Exception {
        if (connection != null) { try { manager.rollback(transaction); } finally { connection.close(); } }
    }
    private void crear(String usuario, String dni) {
        usuarios.crear(new UsuarioController.CrearUsuario("Dato que no debe prevalecer",usuario,"ClaveTemporal2026!","ALMACEN",null,"María José","Muñoz Pérez","MARIA@EXAMPLE.COM","987654321",dni),
            UsernamePasswordAuthenticationToken.authenticated("admin",null,List.of()));
    }
    @Test void registroPerfilYEdicionCompartenLosDatosSinCambiarCredencialesNiRol() {
        crear("maria", "01234567");
        crear("otra", "01234568");
        var inicial = perfiles.consultar("maria");
        assertEquals("María José Muñoz Pérez", inicial.nombreCompleto());
        assertEquals("maria@example.com", inicial.correo());
        assertEquals("01234567", inicial.dni());
        String hash = jdbc.queryForObject("SELECT clave_hash FROM usuario WHERE nombre_usuario='maria'",String.class);
        var actualizado = perfiles.actualizarDatos("maria",new DatosPersonales("María","Muñoz","nuevo@example.com","912345678","01234567"));
        assertEquals("María Muñoz",actualizado.nombreCompleto());
        assertEquals("912345678",perfiles.consultar("maria").telefono());
        assertEquals("987654321",perfiles.consultar("otra").telefono());
        assertEquals("ALMACEN",actualizado.rolCodigo());
        assertEquals(hash,jdbc.queryForObject("SELECT clave_hash FROM usuario WHERE nombre_usuario='maria'",String.class));
        assertEquals(0L,jdbc.queryForObject("SELECT sesion_version FROM usuario WHERE nombre_usuario='maria'",Long.class));
    }
    @Test void laMigracionConservaLasCuentasAntiguasSinInventarDatos() {
        usuarios.crear(new UsuarioController.CrearUsuario("Nombre antiguo intacto","antiguo","ClaveTemporal2026!","ALMACEN",null),null);
        var perfil=perfiles.consultar("antiguo");
        assertEquals("Nombre antiguo intacto",perfil.nombreCompleto());
        assertNull(perfil.nombres()); assertNull(perfil.dni());
        assertEquals("Ana Lima",perfiles.actualizarDatos("antiguo",new DatosPersonales("Ana","Lima","ana@example.com","987654321","01234567")).nombreCompleto());
    }
    @Test void noPermiteReutilizarElDniDeOtraCuenta() {
        crear("maria","01234567"); crear("otra","01234568");
        var error=assertThrows(ResponseStatusException.class,()->perfiles.actualizarDatos("otra",new DatosPersonales("Ana","Lima","ana@example.com","987654321","01234567")));
        assertEquals(409,error.getStatusCode().value());
    }
}
